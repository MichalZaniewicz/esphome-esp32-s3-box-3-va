"""Generuje base/faces/picker.yaml - zywy wybor postaci z Home Assistant.

Dlaczego generowany: pakiet nosi TABLICE liczb kazdej postaci z grafika, a te
liczby leza juz w base/faces/*.yaml. Przepisane recznie rozjechalyby sie z
oryginalem przy pierwszej poprawce geometrii i nikt by tego nie zauwazyl - to
dokladnie ta pulapka, ktora opisuje scripts/check_generated.py.

Zrodlem prawdy zostaja pliki postaci. Ten skrypt tylko je czyta.

Uzycie:  python scripts/gen/gen_picker.py
"""
import io
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
FACES = os.path.join(REPO, "base", "faces")
OUT = os.path.join(FACES, "picker.yaml")

# Kolejnosc pol w tablicy. Zmiana tutaj = zmiana enuma w wygenerowanym C++.
INTS = [
    "center_x", "eye_offset", "eye_w", "eye_h", "eye_h_wide", "eye_h_think",
    "eye_h_narrow", "eye_h_shut", "pupil_w", "pupil_h", "pupil_dilate",
    "pupil_shrink", "gaze_dx", "mouth_w", "mouth_h", "mouth_open_h",
    "mouth_small_w", "mouth_think_w", "mouth_o_w", "mouth_o_h",
    "mouth_alarm_w", "mouth_alarm_h", "mouth_error_w", "listen_pulse",
    "shake_dx", "idle_cycle", "eye_y", "mouth_y", "eye_radius",
    "mouth_radius", "pupil_radius",
]
COLORS = ["color", "mouth_color", "pupil_color", "alarm_color"]
FIELDS = INTS + COLORS

SUB = re.compile(r"^  (face_[a-z_0-9]+):\s*(.+?)\s*$")


def subs(path):
    out, inside = {}, False
    for line in io.open(path, encoding="utf-8"):
        if line.startswith("substitutions:"):
            inside = True
            continue
        if inside:
            # Pusta linia i komentarz nie koncza bloku. Wersja, ktora tego nie
            # wiedziala, urywala sie na komentarzu w kolumnie 0 w srodku bloku
            # (franky, genie, momo, wizard maja taki) i cicho dawala tym
            # postaciom geometrie domyslna, czyli pipa.
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            if not line.startswith("  "):
                break
            m = SUB.match(line)
            if m:
                v = m.group(2)
                if v[0] in "'\"":
                    v = v[1:v.index(v[0], 1)]
                else:
                    v = v.split("#")[0].strip()
                out[m.group(1)] = v
    return out


def characters():
    """Postacie z grafika, w kolejnosci alfabetycznej. Rysujace sie same nie maja
    czego tu ustawiac - one nie uzywaja silnika twarzy."""
    engine = subs(os.path.join(REPO, "base", "screens", "face.yaml"))
    out = []
    for fn in sorted(os.listdir(FACES)):
        if not fn.endswith(".yaml") or fn == "picker.yaml":
            continue
        s = subs(os.path.join(FACES, fn))
        if "face_background_file" not in s:
            continue
        merged = dict(engine)
        merged.update(s)
        vals = []
        for f in FIELDS:
            v = merged["face_" + f]
            vals.append(int(v, 16) if v.lower().startswith("0x") else int(v))
        out.append((fn[:-5], vals))
    return out


def main():
    chars = characters()
    w = max(len(n) for n, _ in chars)

    rows = []
    for name, vals in chars:
        ints = ", ".join(f"{v:>4}" for v in vals[:len(INTS)])
        cols = ", ".join(f"0x{v:06X}" for v in vals[len(INTS):])
        rows.append(f'            {{"{name}",{" " * (w - len(name))} '
                    f'{{{ints}, {cols}}}}},')
    table = "\n".join(rows)

    fields = ", ".join(f.upper() for f in FIELDS)
    enum_lines = []
    line = "          enum { "
    for i, f in enumerate(FIELDS):
        piece = f.upper() + ("," if i < len(FIELDS) - 1 else " };")
        if len(line) + len(piece) > 96:
            enum_lines.append(line)
            line = "                 "
        line += piece + " "
    enum_lines.append(line.rstrip())
    enum = "\n".join(enum_lines)

    names = ", ".join(n for n, _ in chars)

    yaml = f'''###############################################################################
# Live character picker: an "Assistant" select in Home Assistant.
#
# GENERATED by scripts/gen/gen_picker.py - do not edit. The numbers below are
# copied out of base/faces/*.yaml, which stay the source of truth; edit a
# character there and run the generator.
#
# An OPTIONAL package that rides on base/screens/face.yaml. Add it AFTER the
# character:
#
#   substitutions:
#     assistant: pip          # compiled in, and the first option
#     pick_2: rufus           # three more, compiled in alongside it
#     pick_3: mandrake
#     pick_4: hacker
#
#   packages:
#     core:
#       files:
#         - base/core.yaml
#         - base/faces/${{assistant}}.yaml
#         - base/faces/picker.yaml
#
# Pick one in Home Assistant and the artwork, the geometry and the colours all
# change on the spot, no rebuild, and the choice survives a reboot.
#
# WHY FOUR AND NOT ALL {len(chars)}: the artwork is the cost. Each character's PNG is
# 320x240 RGB565 = 150 KB of flash, compiled in whether or not it is ever shown.
# Four is 450 KB on top of the one you already had, which this board can afford;
# twenty-five could not. WHICH four is a compile-time decision, switching between
# them is not.
#
# The four names must be DIFFERENT. A select cannot carry the same option twice,
# and ESPHome will tell you so at build time.
#
# Only characters WITH ARTWORK can be picked ({names}).
# The self-drawing ones - aura, bit, crt, iris, kitt, nixie, pixel, rain, scope,
# vu - are whole pages of their own rather than numbers on top of a picture, so
# there is nothing here to swap.
###############################################################################

substitutions:
  pick_2: rufus
  pick_3: mandrake
  pick_4: hacker

esphome:
  on_boot:
    - priority: 800
      then:
        - logger.log:
            level: INFO
            format: "package: faces/picker.yaml (live Assistant select)"
    # A template select restores its value but does NOT fire on_value at boot,
    # so the restored character is applied here. -200 is late enough that LVGL
    # is up and the face page exists.
    - priority: -200
      then:
        - script.execute: apply_assistant

# The other three characters' artwork. The first option's image is the engine's
# own `face_bg`, so naming ${{assistant}} again here would compile the same
# 150 KB twice.
image:
  - platform: file
    id: face_bg_2
    file: https://github.com/MichalZaniewicz/esphome-esp32-s3-box-3-va/raw/main/base/faces/${{pick_2}}.png
    resize: 320x240
    type: RGB565
  - platform: file
    id: face_bg_3
    file: https://github.com/MichalZaniewicz/esphome-esp32-s3-box-3-va/raw/main/base/faces/${{pick_3}}.png
    resize: 320x240
    type: RGB565
  - platform: file
    id: face_bg_4
    file: https://github.com/MichalZaniewicz/esphome-esp32-s3-box-3-va/raw/main/base/faces/${{pick_4}}.png
    resize: 320x240
    type: RGB565

select:
  - platform: template
    id: assistant_select
    name: Assistant
    icon: "mdi:account-switch"
    optimistic: true
    restore_value: true
    entity_category: config
    options: ["${{assistant}}", "${{pick_2}}", "${{pick_3}}", "${{pick_4}}"]
    initial_option: "${{assistant}}"
    on_value:
      - script.execute: apply_assistant

script:
  - id: apply_assistant
    mode: single
    then:
      # Everything a character IS, as numbers. The engine reads most of these
      # every tick out of the fg_* globals; the rest - vertical positions, corner
      # radii, colours - it never touches, so they are written straight to the
      # widgets here.
      - lambda: |-
          struct Spec {{ const char *name; int32_t v[{len(FIELDS)}]; }};
{enum}
          static const Spec SPECS[] = {{
{table}
          }};
          const std::string s = id(assistant_select).current_option();
          const Spec *f = nullptr;
          for (auto &sp : SPECS) if (s == sp.name) {{ f = &sp; break; }}
          if (f == nullptr) return;          // not one of ours, leave the face alone
          const int32_t *v = f->v;

          id(fg_center_x) = v[CENTER_X];          id(fg_eye_offset) = v[EYE_OFFSET];
          id(fg_eye_w) = v[EYE_W];                id(fg_eye_h) = v[EYE_H];
          id(fg_eye_h_wide) = v[EYE_H_WIDE];      id(fg_eye_h_think) = v[EYE_H_THINK];
          id(fg_eye_h_narrow) = v[EYE_H_NARROW];  id(fg_eye_h_shut) = v[EYE_H_SHUT];
          id(fg_pupil_w) = v[PUPIL_W];            id(fg_pupil_h) = v[PUPIL_H];
          id(fg_pupil_dilate) = v[PUPIL_DILATE];  id(fg_pupil_shrink) = v[PUPIL_SHRINK];
          id(fg_gaze_dx) = v[GAZE_DX];            id(fg_mouth_w) = v[MOUTH_W];
          id(fg_mouth_h) = v[MOUTH_H];            id(fg_mouth_open_h) = v[MOUTH_OPEN_H];
          id(fg_mouth_small_w) = v[MOUTH_SMALL_W];id(fg_mouth_think_w) = v[MOUTH_THINK_W];
          id(fg_mouth_o_w) = v[MOUTH_O_W];        id(fg_mouth_o_h) = v[MOUTH_O_H];
          id(fg_mouth_alarm_w) = v[MOUTH_ALARM_W];id(fg_mouth_alarm_h) = v[MOUTH_ALARM_H];
          id(fg_mouth_error_w) = v[MOUTH_ERROR_W];id(fg_listen_pulse) = v[LISTEN_PULSE];
          id(fg_shake_dx) = v[SHAKE_DX];          id(fg_idle_cycle) = v[IDLE_CYCLE];
          id(fg_color) = v[COLOR];                id(fg_mouth_color) = v[MOUTH_COLOR];
          id(fg_alarm_color) = v[ALARM_COLOR];

          lv_obj_t *el = id(face_eye_l), *er = id(face_eye_r);
          lv_obj_t *pl = id(face_pupil_l), *pr = id(face_pupil_r);
          lv_obj_t *mo = id(face_mouth_obj);
          // Vertical position: the tick only ever writes x, because y is a
          // constant of the character - which is precisely why it has to be
          // written here, and why forgetting it leaves the new eyes at the old
          // one's height.
          lv_obj_set_y(el, v[EYE_Y]);   lv_obj_set_y(er, v[EYE_Y]);
          lv_obj_set_y(pl, v[EYE_Y]);   lv_obj_set_y(pr, v[EYE_Y]);
          lv_obj_set_y(mo, v[MOUTH_Y]);
          lv_obj_set_style_radius(el, v[EYE_RADIUS], LV_PART_MAIN);
          lv_obj_set_style_radius(er, v[EYE_RADIUS], LV_PART_MAIN);
          lv_obj_set_style_radius(pl, v[PUPIL_RADIUS], LV_PART_MAIN);
          lv_obj_set_style_radius(pr, v[PUPIL_RADIUS], LV_PART_MAIN);
          lv_obj_set_style_radius(mo, v[MOUTH_RADIUS], LV_PART_MAIN);
          // Paint the resting colours and declare the face un-alarmed. If it
          // was mid-alarm, face_expr was just reset too, so the next tick runs
          // the timer branch's entry code and tints it red again.
          lv_obj_set_style_bg_color(el, lv_color_hex(v[COLOR]), LV_PART_MAIN);
          lv_obj_set_style_bg_color(er, lv_color_hex(v[COLOR]), LV_PART_MAIN);
          lv_obj_set_style_bg_color(pl, lv_color_hex(v[PUPIL_COLOR]), LV_PART_MAIN);
          lv_obj_set_style_bg_color(pr, lv_color_hex(v[PUPIL_COLOR]), LV_PART_MAIN);
          lv_obj_set_style_bg_color(mo, lv_color_hex(v[MOUTH_COLOR]), LV_PART_MAIN);
          id(face_alarm_tint) = false;

      # Stale caches and the forced re-apply. Without this the face keeps the
      # previous character's shape until something happens to differ.
      - script.execute: face_geometry_changed

      # The artwork. `lvgl.image.update` takes an image known at compile time,
      # so this is four branches rather than a lookup - and it is the only place
      # the picker cares WHICH slot a name is in.
      - if:
          condition:
            lambda: return id(assistant_select).current_option() == "${{pick_2}}";
          then:
            - lvgl.image.update: {{ id: face_bg_obj, src: face_bg_2 }}
      - if:
          condition:
            lambda: return id(assistant_select).current_option() == "${{pick_3}}";
          then:
            - lvgl.image.update: {{ id: face_bg_obj, src: face_bg_3 }}
      - if:
          condition:
            lambda: return id(assistant_select).current_option() == "${{pick_4}}";
          then:
            - lvgl.image.update: {{ id: face_bg_obj, src: face_bg_4 }}
      - if:
          condition:
            lambda: return id(assistant_select).current_option() == "${{assistant}}";
          then:
            - lvgl.image.update: {{ id: face_bg_obj, src: face_bg }}
'''
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(yaml)
    print(f"picker.yaml: {len(chars)} postaci w tablicy ({names})")


if __name__ == "__main__":
    main()
